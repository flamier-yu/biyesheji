-- ============================================================
-- 外部 MySQL 初始化与远程访问授权
-- ============================================================
-- 适用场景：MySQL 部署在宿主机或独立服务器，应用在 Docker 容器中运行。
--
-- 执行方式（在 MySQL 所在机器上）：
--   mysql -uroot -p < deploy/init-external-db.sql
--
-- 执行后请检查两处系统配置：
--   1) bind-address     见文末说明
--   2) 防火墙           见文末说明
-- ============================================================

-- ------------------------------------------------------------
-- 一、建库（如已存在可跳过）
-- ------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS `biyesheji`
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_general_ci;

-- ------------------------------------------------------------
-- 二、创建应用专用账号
-- ------------------------------------------------------------
-- 为什么不用 root？
--   ① 最小权限原则，应用只需业务库权限，不需要 DROP USER / FILE 等管理权限
--   ② root 一旦泄露影响面是整台 MySQL 实例
--   ③ 便于审计与随时吊销

-- 为什么是 '%' 而不是 'localhost'？
--   容器访问宿主机时，MySQL 看到的来源 IP 是 Docker 网桥地址
--   （通常是 172.17.0.1 / 172.18.0.1 这类），而不是 127.0.0.1，
--   所以必须允许非本机来源。生产环境可收紧为具体网段，如 '172.%'。

DROP USER IF EXISTS 'pms'@'%';
CREATE USER 'pms'@'%' IDENTIFIED BY 'Pms@2026';

-- 只授予业务库权限（不含其他库）
GRANT ALL PRIVILEGES ON `biyesheji`.* TO 'pms'@'%';

-- 如果应用需要用 mysqldump 做备份，还需补这两个权限：
-- GRANT SELECT, LOCK TABLES, SHOW VIEW, EVENT, TRIGGER ON `biyesheji`.* TO 'pms'@'%';

FLUSH PRIVILEGES;

-- ------------------------------------------------------------
-- 三、验证授权结果
-- ------------------------------------------------------------
SELECT User, Host FROM mysql.user WHERE User = 'pms';

SHOW GRANTS FOR 'pms'@'%';

-- ============================================================
-- 四、还需要在系统层面做的两件事
-- ============================================================
--
-- 【1】检查 bind-address
--   MySQL 默认可能只监听 127.0.0.1，导致外部连不上。
--   查看方式：
--     SHOW VARIABLES LIKE 'bind_address';
--   结果若是 127.0.0.1，需要改配置文件：
--     · Windows : C:\ProgramData\MySQL\MySQL Server 8.0\my.ini
--     · Linux   : /etc/mysql/mysql.conf.d/mysqld.cnf
--   把 bind-address 改为 0.0.0.0（或直接注释掉该行），然后重启 MySQL 服务。
--   ⚠️ 改成 0.0.0.0 意味着监听所有网卡，务必配合防火墙限制来源。
--
-- 【2】确认端口是否可达
--   · MySQL 与 Docker 同机：容器走 Docker 网桥访问，一般不经过系统防火墙，
--     但 Windows 的"专用网络防火墙"可能拦截，需放行 3306。
--   · MySQL 在另一台机器：需要在该机器放行 3306，例如
--       firewall-cmd --permanent --add-port=3306/tcp && firewall-cmd --reload
--       （或 iptables / 云服务器安全组放行）
--
-- 【3】验证连接（在 MySQL 所在机器上执行）
--   mysql -h <对方IP> -P 3306 -u pms -p -e "SELECT 1;"
--   能返回结果即说明远程访问已通。
-- ============================================================
